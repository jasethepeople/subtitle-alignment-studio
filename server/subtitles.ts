export type ParsedCue = {
  sequence: number;
  startMs: number;
  endMs: number;
  plainText: string;
  richText: string;
  assStyle?: string;
  speaker?: string;
  sourceMetadata?: Record<string, unknown>;
};

export type ParsedSubtitle = {
  format: "srt" | "ass";
  cues: ParsedCue[];
  styleProfile?: string;
};

const ASS_DEFAULT_HEADER = `[Script Info]\n; Script generated by SyncForge Studio\nScriptType: v4.00+\n\n[V4+ Styles]\nFormat: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding\nStyle: Default,Arial,42,&H00FFFFFF,&H000000FF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,2,0,2,30,30,30,1\n\n[Events]\nFormat: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text`;

function normalize(content: string) {
  return content.replace(/^\uFEFF/, "").replace(/\r\n/g, "\n").replace(/\r/g, "\n");
}

export function parseSubtitle(content: string, filename: string): ParsedSubtitle {
  const extension = filename.toLowerCase().split(".").pop();
  if (extension === "srt") return parseSrt(content);
  if (extension === "ass") return parseAss(content);
  throw new Error("Only .srt and .ass subtitle files are supported.");
}

export function parseSrt(content: string): ParsedSubtitle {
  const blocks = normalize(content).trim().split(/\n{2,}/).filter(Boolean);
  const cues: ParsedCue[] = [];
  for (const block of blocks) {
    const lines = block.split("\n");
    const timeIndex = lines.findIndex(line => line.includes("-->"));
    if (timeIndex === -1) continue;
    const [startToken, endToken] = lines[timeIndex].split("-->").map(value => value.trim().split(/\s+/)[0]);
    const startMs = parseSrtTimestamp(startToken);
    const endMs = parseSrtTimestamp(endToken);
    if (startMs === null || endMs === null || endMs <= startMs) continue;
    const richText = lines.slice(timeIndex + 1).join("\n");
    cues.push({
      sequence: cues.length + 1,
      startMs,
      endMs,
      richText,
      plainText: stripSubtitleTags(richText),
      sourceMetadata: { source: "srt", cueIdentifier: timeIndex > 0 ? lines.slice(0, timeIndex).join(" ") : undefined },
    });
  }
  return { format: "srt", cues };
}

export function parseAss(content: string): ParsedSubtitle {
  const normalized = normalize(content);
  const eventIndex = normalized.search(/^\[Events\]\s*$/im);
  if (eventIndex === -1) throw new Error("Invalid ASS file: [Events] section is missing.");
  const styleProfile = normalized.slice(0, eventIndex).trimEnd();
  const eventLines = normalized.slice(eventIndex).split("\n");
  const formatLine = eventLines.find(line => /^Format\s*:/i.test(line));
  const fields = (formatLine?.split(":").slice(1).join(":") || "Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text")
    .split(",").map(item => item.trim().toLowerCase());
  const cues: ParsedCue[] = [];
  for (const line of eventLines) {
    if (!/^Dialogue\s*:/i.test(line)) continue;
    const values = splitAssDialogue(line.split(":").slice(1).join(":"), fields.length);
    const startMs = parseAssTimestamp(values[fields.indexOf("start")] || "");
    const endMs = parseAssTimestamp(values[fields.indexOf("end")] || "");
    if (startMs === null || endMs === null || endMs <= startMs) continue;
    const richText = values[fields.indexOf("text")] || "";
    cues.push({
      sequence: cues.length + 1,
      startMs,
      endMs,
      richText,
      plainText: stripSubtitleTags(richText),
      assStyle: values[fields.indexOf("style")] || "Default",
      speaker: values[fields.indexOf("name")] || undefined,
      sourceMetadata: { source: "ass", fields, rawValues: values },
    });
  }
  return { format: "ass", cues, styleProfile };
}

export function serializeSrt(cues: Pick<ParsedCue, "sequence" | "startMs" | "endMs" | "richText">[]) {
  return cues.map((cue, index) => `${cue.sequence || index + 1}\n${formatSrtTimestamp(cue.startMs)} --> ${formatSrtTimestamp(cue.endMs)}\n${cue.richText}`).join("\n\n") + "\n";
}

export function serializeAss(cues: Pick<ParsedCue, "startMs" | "endMs" | "richText" | "assStyle" | "speaker">[], styleProfile?: string | null) {
  const header = styleProfile?.trim() || ASS_DEFAULT_HEADER;
  const preparedHeader = /\[Events\]/i.test(header) ? header : `${header}\n\n[Events]\nFormat: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text`;
  const rows = cues.map(cue => `Dialogue: 0,${formatAssTimestamp(cue.startMs)},${formatAssTimestamp(cue.endMs)},${cue.assStyle || "Default"},${cue.speaker || ""},0,0,0,,${srtMarkupToAss(cue.richText)}`);
  return `${preparedHeader.trimEnd()}\n${rows.join("\n")}\n`;
}

export function serializeVtt(cues: Pick<ParsedCue, "sequence" | "startMs" | "endMs" | "richText">[]) {
  const body = cues.map((cue, index) => `${cue.sequence || index + 1}\n${formatVttTimestamp(cue.startMs)} --> ${formatVttTimestamp(cue.endMs)}\n${assMarkupToVtt(cue.richText)}`).join("\n\n");
  return `WEBVTT\n\n${body}\n`;
}

export function serializePlainText(cues: Pick<ParsedCue, "startMs" | "endMs" | "plainText">[]) {
  return cues.map(cue => `[${formatVttTimestamp(cue.startMs)} → ${formatVttTimestamp(cue.endMs)}]\n${cue.plainText}`).join("\n\n") + "\n";
}

export function formatSrtTimestamp(ms: number) {
  const value = Math.max(0, Math.round(ms));
  const hours = Math.floor(value / 3_600_000);
  const minutes = Math.floor((value % 3_600_000) / 60_000);
  const seconds = Math.floor((value % 60_000) / 1_000);
  const millis = value % 1_000;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")},${String(millis).padStart(3, "0")}`;
}

export function formatAssTimestamp(ms: number) {
  const value = Math.max(0, Math.round(ms));
  const hours = Math.floor(value / 3_600_000);
  const minutes = Math.floor((value % 3_600_000) / 60_000);
  const seconds = Math.floor((value % 60_000) / 1_000);
  const centis = Math.floor((value % 1_000) / 10);
  return `${hours}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}.${String(centis).padStart(2, "0")}`;
}

export function formatVttTimestamp(ms: number) {
  const value = Math.max(0, Math.round(ms));
  const hours = Math.floor(value / 3_600_000);
  const minutes = Math.floor((value % 3_600_000) / 60_000);
  const seconds = Math.floor((value % 60_000) / 1_000);
  const millis = value % 1_000;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}.${String(millis).padStart(3, "0")}`;
}

function parseSrtTimestamp(value: string) {
  const match = /^(\d{1,3}):(\d{2}):(\d{2})[,.](\d{1,3})$/.exec(value);
  if (!match) return null;
  const [, h, m, s, ms] = match;
  return Number(h) * 3_600_000 + Number(m) * 60_000 + Number(s) * 1_000 + Number(ms.padEnd(3, "0"));
}

function parseAssTimestamp(value: string) {
  const match = /^(\d{1,3}):(\d{2}):(\d{2})\.(\d{1,2})$/.exec(value.trim());
  if (!match) return null;
  const [, h, m, s, centis] = match;
  return Number(h) * 3_600_000 + Number(m) * 60_000 + Number(s) * 1_000 + Number(centis.padEnd(2, "0")) * 10;
}

function splitAssDialogue(value: string, fields: number) {
  const output: string[] = [];
  let remaining = value;
  for (let index = 0; index < fields - 1; index += 1) {
    const comma = remaining.indexOf(",");
    if (comma === -1) {
      output.push(remaining.trim());
      remaining = "";
    } else {
      output.push(remaining.slice(0, comma).trim());
      remaining = remaining.slice(comma + 1);
    }
  }
  output.push(remaining);
  return output;
}

export function stripSubtitleTags(value: string) {
  return value.replace(/\{\\[^}]+\}/g, "").replace(/<\/?[^>]+>/g, "").replace(/\\N/g, " ").replace(/\\n/g, " ").trim();
}

function srtMarkupToAss(value: string) {
  return value
    .replace(/<i>/gi, "{\\i1}").replace(/<\/i>/gi, "{\\i0}")
    .replace(/<b>/gi, "{\\b1}").replace(/<\/b>/gi, "{\\b0}")
    .replace(/<u>/gi, "{\\u1}").replace(/<\/u>/gi, "{\\u0}");
}

function assMarkupToVtt(value: string) {
  return value
    .replace(/\{\\i1\}/gi, "<i>").replace(/\{\\i0\}/gi, "</i>")
    .replace(/\{\\b1\}/gi, "<b>").replace(/\{\\b0\}/gi, "</b>")
    .replace(/\{\\u1\}/gi, "<u>").replace(/\{\\u0\}/gi, "</u>")
    .replace(/\{\\[^}]+\}/g, "")
    .replace(/\\N/g, "\n");
}
